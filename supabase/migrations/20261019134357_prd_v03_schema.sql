CREATE FUNCTION private.validate_session_graph() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE target_session uuid; session_row public.sessions;
BEGIN
    IF TG_TABLE_NAME = 'sessions' THEN
        target_session := COALESCE(NEW.id, OLD.id);
    ELSE
        target_session := COALESCE(NEW.session_id, OLD.session_id);
    END IF;
    SELECT * INTO session_row FROM public.sessions WHERE id = target_session FOR UPDATE;
    IF NOT FOUND THEN RETURN NULL; END IF;
    IF session_row.status <> 'needs_review' AND (SELECT count(*) FROM public.session_courts
        WHERE session_id = target_session AND is_active) <> session_row.court_count THEN
        RAISE EXCEPTION 'court_count_mismatch' USING ERRCODE = '23514';
    END IF;
    IF (SELECT count(*) FROM public.session_participants WHERE session_id = target_session
        AND response = 'attending' AND approval = 'approved') > session_row.capacity THEN
        RAISE EXCEPTION 'session_capacity_exceeded' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM public.session_participants participant
        JOIN public.club_participants club_participant ON club_participant.id = participant.club_participant_id
        WHERE participant.session_id = target_session AND
        (club_participant.club_id <> session_row.club_id OR
         (participant.account_id IS NOT NULL AND participant.account_id IS DISTINCT FROM club_participant.account_id))) THEN
        RAISE EXCEPTION 'participant_club_or_account_mismatch' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM public.matches match WHERE match.session_id = target_session AND
        (SELECT count(*) FROM public.match_players WHERE match_id = match.id) <> 4) THEN
        RAISE EXCEPTION 'match_requires_four_players' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM public.matches match JOIN public.match_players player ON player.match_id = match.id
        WHERE match.session_id = target_session AND match.status = 'in_progress'
        GROUP BY player.participant_id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'participant_already_playing' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM public.matches match JOIN public.match_players player ON player.match_id = match.id
        WHERE match.session_id = target_session AND match.status <> 'cancelled' AND match.round_index IS NOT NULL
        GROUP BY match.round_index, player.participant_id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'participant_round_overlap' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (SELECT 1 FROM public.matches match LEFT JOIN public.results result ON result.match_id = match.id
        WHERE match.session_id = target_session AND
        ((match.status = 'completed' AND (result.match_id IS NULL OR NOT result.is_valid)) OR
         (result.is_valid AND match.status <> 'completed'))) THEN
        RAISE EXCEPTION 'result_match_state_mismatch' USING ERRCODE = '23514';
    END IF;
    IF session_row.status = 'completed' AND EXISTS (SELECT 1 FROM public.matches
        WHERE session_id = target_session AND status IN ('pending', 'in_progress')) THEN
        RAISE EXCEPTION 'unfinished_matches' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE FUNCTION private.validate_result_graph() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE match_status text;
BEGIN
    SELECT status INTO match_status FROM public.matches WHERE id = COALESCE(NEW.match_id, OLD.match_id);
    IF EXISTS (SELECT 1 FROM public.results WHERE match_id = COALESCE(NEW.match_id, OLD.match_id) AND is_valid)
        IS DISTINCT FROM (match_status = 'completed') THEN
        RAISE EXCEPTION 'result_match_state_mismatch' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE FUNCTION private.protect_match_players() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE target_match public.matches;
BEGIN
    SELECT * INTO target_match FROM public.matches WHERE id = COALESCE(NEW.match_id, OLD.match_id);
    PERFORM 1 FROM public.sessions WHERE id = target_match.session_id FOR UPDATE;
    IF target_match.status <> 'pending' THEN
        RAISE EXCEPTION 'started_match_players_immutable' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
CREATE TRIGGER match_players_immutable BEFORE UPDATE OR DELETE ON public.match_players
    FOR EACH ROW EXECUTE FUNCTION private.protect_match_players();

CREATE FUNCTION private.protect_match_identity() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    PERFORM 1 FROM public.sessions WHERE id=OLD.session_id FOR UPDATE;
    IF OLD.session_id IS DISTINCT FROM NEW.session_id OR
        (OLD.status<>'pending' AND ROW(OLD.court_id,OLD.round_index,OLD.schedule_version,OLD.started_at)
            IS DISTINCT FROM ROW(NEW.court_id,NEW.round_index,NEW.schedule_version,NEW.started_at)) THEN
        RAISE EXCEPTION 'started_match_identity_immutable' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER match_identity_immutable BEFORE UPDATE ON public.matches
    FOR EACH ROW EXECUTE FUNCTION private.protect_match_identity();

CREATE FUNCTION private.validate_club_owner() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE target_club uuid; club_row public.clubs;
BEGIN
    IF TG_TABLE_NAME = 'clubs' THEN target_club := COALESCE(NEW.id, OLD.id);
    ELSE target_club := COALESCE(NEW.club_id, OLD.club_id); END IF;
    SELECT * INTO club_row FROM public.clubs WHERE id = target_club FOR UPDATE;
    IF club_row.status = 'active' AND NOT EXISTS (SELECT 1 FROM public.memberships
        WHERE club_id = target_club AND account_id = club_row.owner_account_id
          AND role = 'owner' AND status = 'approved') THEN
        RAISE EXCEPTION 'club_requires_matching_owner' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER club_owner_consistency AFTER INSERT OR UPDATE ON public.clubs
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION private.validate_club_owner();
CREATE CONSTRAINT TRIGGER membership_owner_consistency AFTER INSERT OR UPDATE OR DELETE ON public.memberships
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION private.validate_club_owner();

