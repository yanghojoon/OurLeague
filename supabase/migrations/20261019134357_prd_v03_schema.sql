CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA private TO authenticated, anon;
ALTER DEFAULT PRIVILEGES IN SCHEMA private REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

CREATE TABLE IF NOT EXISTS public."Player" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    name text NOT NULL
);
CREATE TABLE IF NOT EXISTS public."Club" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS public."Club_Participants" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    player_id bigint NOT NULL REFERENCES public."Player"(id) ON UPDATE CASCADE ON DELETE CASCADE,
    club_id bigint NOT NULL REFERENCES public."Club"(id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public."GameByDay" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at date NOT NULL,
    ended_at date NOT NULL,
    name text,
    games bigint[]
);
CREATE TABLE IF NOT EXISTS public."Game" (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    score bigint[],
    team_a bigint[],
    team_b bigint[]
);

CREATE TABLE public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    display_name text NOT NULL CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 40),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.clubs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
    description text NOT NULL DEFAULT '',
    owner_account_id uuid REFERENCES auth.users(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'closed', 'needs_owner')),
    legacy_id bigint UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (status <> 'active' OR owner_account_id IS NOT NULL)
);
CREATE INDEX clubs_owner_idx ON public.clubs(owner_account_id);

CREATE TABLE public.memberships (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    club_id uuid NOT NULL REFERENCES public.clubs(id) ON DELETE RESTRICT,
    account_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'inactive')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (club_id, account_id),
    CHECK (role <> 'owner' OR status = 'approved')
);
CREATE INDEX memberships_account_idx ON public.memberships(account_id, club_id);
CREATE UNIQUE INDEX memberships_one_owner_idx ON public.memberships(club_id) WHERE role = 'owner';

CREATE TABLE public.club_participants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    club_id uuid NOT NULL REFERENCES public.clubs(id) ON DELETE RESTRICT,
    account_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    display_name text NOT NULL CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 40),
    label text,
    is_active boolean NOT NULL DEFAULT true,
    legacy_player_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, club_id),
    UNIQUE (club_id, legacy_player_id)
);
CREATE UNIQUE INDEX club_participants_account_club_idx ON public.club_participants(club_id, account_id)
    WHERE account_id IS NOT NULL AND is_active;
CREATE INDEX club_participants_account_idx ON public.club_participants(account_id);

CREATE TABLE public.sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    club_id uuid NOT NULL REFERENCES public.clubs(id) ON DELETE RESTRICT,
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 100),
    starts_at timestamptz,
    ends_at timestamptz,
    location text,
    capacity integer NOT NULL DEFAULT 16 CHECK (capacity BETWEEN 4 AND 32),
    court_count integer NOT NULL DEFAULT 1 CHECK (court_count BETWEEN 1 AND 4),
    round_count integer NOT NULL DEFAULT 3 CHECK (round_count BETWEEN 1 AND 12),
    attendance_deadline timestamptz,
    notice text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'recruiting'
        CHECK (status IN ('needs_review', 'recruiting', 'confirmed', 'in_progress', 'completed', 'cancelled')),
    roster_version integer NOT NULL DEFAULT 0 CHECK (roster_version >= 0),
    schedule_version integer NOT NULL DEFAULT 0 CHECK (schedule_version >= 0),
    schedule_stale boolean NOT NULL DEFAULT true,
    seed bigint,
    legacy_id bigint UNIQUE,
    legacy_start_date date,
    legacy_end_date date,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, club_id),
    CHECK (ends_at > starts_at),
    CHECK (attendance_deadline <= starts_at),
    CHECK (status IN ('needs_review', 'cancelled') OR
        (starts_at IS NOT NULL AND ends_at IS NOT NULL AND attendance_deadline IS NOT NULL AND
         location IS NOT NULL AND char_length(btrim(location)) > 0))
);
CREATE INDEX sessions_club_date_idx ON public.sessions(club_id, starts_at DESC);

CREATE TABLE public.session_courts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id uuid NOT NULL REFERENCES public.sessions(id) ON DELETE RESTRICT,
    name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 40),
    position integer NOT NULL CHECK (position BETWEEN 1 AND 4),
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (id, session_id),
    UNIQUE (session_id, position)
);

CREATE TABLE public.session_participants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id uuid NOT NULL REFERENCES public.sessions(id) ON DELETE RESTRICT,
    club_participant_id uuid REFERENCES public.club_participants(id) ON DELETE RESTRICT,
    account_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    display_name text NOT NULL CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 40),
    response text NOT NULL DEFAULT 'attending' CHECK (response IN ('attending', 'declined')),
    approval text NOT NULL DEFAULT 'pending' CHECK (approval IN ('pending', 'approved', 'rejected')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, session_id),
    UNIQUE (session_id, club_participant_id),
    UNIQUE (session_id, account_id)
);
CREATE INDEX session_participants_club_participant_idx ON public.session_participants(club_participant_id);
CREATE INDEX session_participants_account_idx ON public.session_participants(account_id);

CREATE TABLE public.matches (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id uuid NOT NULL REFERENCES public.sessions(id) ON DELETE RESTRICT,
    round_index integer CHECK (round_index BETWEEN 1 AND 12),
    court_id uuid,
    schedule_version integer NOT NULL CHECK (schedule_version >= 0),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'completed', 'aborted', 'cancelled')),
    started_at timestamptz,
    finished_at timestamptz,
    legacy_id bigint UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, session_id),
    FOREIGN KEY (court_id, session_id) REFERENCES public.session_courts(id, session_id) ON DELETE RESTRICT,
    CHECK (legacy_id IS NOT NULL OR (round_index IS NOT NULL AND court_id IS NOT NULL)),
    CHECK (legacy_id IS NOT NULL OR status NOT IN ('in_progress', 'completed', 'aborted') OR started_at IS NOT NULL),
    CHECK (legacy_id IS NOT NULL OR status NOT IN ('completed', 'aborted') OR finished_at IS NOT NULL),
    CHECK (finished_at >= started_at)
);
CREATE INDEX matches_session_idx ON public.matches(session_id);
CREATE INDEX matches_court_idx ON public.matches(court_id, session_id);
CREATE UNIQUE INDEX matches_round_court_idx ON public.matches(session_id, round_index, court_id)
    WHERE status <> 'cancelled';
CREATE UNIQUE INDEX matches_active_court_idx ON public.matches(session_id, court_id) WHERE status = 'in_progress';

CREATE TABLE public.match_players (
    match_id uuid NOT NULL,
    session_id uuid NOT NULL,
    participant_id uuid NOT NULL,
    team text NOT NULL CHECK (team IN ('a', 'b')),
    slot integer NOT NULL CHECK (slot IN (1, 2)),
    PRIMARY KEY (match_id, participant_id),
    UNIQUE (match_id, team, slot),
    FOREIGN KEY (match_id, session_id) REFERENCES public.matches(id, session_id) ON DELETE CASCADE,
    FOREIGN KEY (participant_id, session_id) REFERENCES public.session_participants(id, session_id) ON DELETE RESTRICT
);
CREATE INDEX match_players_participant_idx ON public.match_players(participant_id, session_id);
CREATE INDEX match_players_session_idx ON public.match_players(session_id);

CREATE TABLE public.results (
    match_id uuid PRIMARY KEY REFERENCES public.matches(id) ON DELETE RESTRICT,
    winner text NOT NULL CHECK (winner IN ('a', 'b')),
    score_a integer CHECK (score_a >= 0),
    score_b integer CHECK (score_b >= 0),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    is_valid boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((score_a IS NULL AND score_b IS NULL) OR
        (score_a IS NOT NULL AND score_b IS NOT NULL AND
         ((winner = 'a' AND score_a > score_b) OR (winner = 'b' AND score_b > score_a))))
);

CREATE TABLE public.result_revisions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    match_id uuid NOT NULL REFERENCES public.matches(id) ON DELETE RESTRICT,
    old_result jsonb,
    new_result jsonb NOT NULL,
    reason text NOT NULL CHECK (char_length(btrim(reason)) > 0),
    actor_account_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX result_revisions_match_idx ON public.result_revisions(match_id, created_at);
CREATE INDEX result_revisions_actor_idx ON public.result_revisions(actor_account_id);

CREATE TABLE private.invitations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    club_id uuid NOT NULL REFERENCES public.clubs(id) ON DELETE RESTRICT,
    session_id uuid REFERENCES public.sessions(id) ON DELETE RESTRICT,
    kind text NOT NULL CHECK (kind IN ('membership', 'guest')),
    token_hash text NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((kind = 'guest') = (session_id IS NOT NULL))
);
CREATE INDEX invitations_club_idx ON private.invitations(club_id);
CREATE INDEX invitations_session_idx ON private.invitations(session_id);

CREATE TABLE private.guest_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    invitation_id uuid NOT NULL REFERENCES private.invitations(id) ON DELETE RESTRICT,
    participant_id uuid NOT NULL UNIQUE REFERENCES public.session_participants(id) ON DELETE RESTRICT,
    token_hash text NOT NULL UNIQUE CHECK (char_length(token_hash) = 64),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX guest_sessions_invitation_idx ON private.guest_sessions(invitation_id);

CREATE TABLE private.command_receipts (
    actor_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    request_id uuid NOT NULL,
    operation text NOT NULL,
    payload_hash text NOT NULL,
    result jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (actor_id, request_id)
);

CREATE FUNCTION private.can_read_club(target_club uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT EXISTS (SELECT 1 FROM public.memberships membership
        WHERE membership.club_id = target_club AND membership.account_id = (SELECT auth.uid())
          AND membership.status = 'approved');
$$;
CREATE FUNCTION private.is_club_owner(target_club uuid) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT EXISTS (SELECT 1 FROM public.clubs club WHERE club.id = target_club
        AND club.owner_account_id = (SELECT auth.uid()) AND club.status = 'active');
$$;
GRANT EXECUTE ON FUNCTION private.can_read_club(uuid), private.is_club_owner(uuid) TO authenticated;

