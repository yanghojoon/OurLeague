CREATE VIEW public.participant_stats WITH (security_invoker = true) AS
WITH player_outcomes AS (
    SELECT session.club_id, participant.club_participant_id AS participant_id,
        count(*) FILTER (WHERE match.status IN ('in_progress', 'completed', 'aborted')) AS appearances,
        count(*) FILTER (WHERE match.status = 'completed' AND result.is_valid) AS completed_matches,
        count(*) FILTER (WHERE match.status = 'completed' AND result.is_valid AND player.team = result.winner) AS wins,
        count(*) FILTER (WHERE match.status = 'completed' AND result.is_valid AND player.team <> result.winner) AS losses
    FROM public.match_players player
    JOIN public.matches match ON match.id = player.match_id
    JOIN public.sessions session ON session.id = match.session_id
    JOIN public.session_participants participant ON participant.id = player.participant_id
    LEFT JOIN public.results result ON result.match_id = match.id
    WHERE participant.club_participant_id IS NOT NULL
    GROUP BY session.club_id, participant.club_participant_id
)
SELECT participant.club_id, participant.id AS participant_id, participant.display_name,
    COALESCE(outcome.wins, 0) AS wins, COALESCE(outcome.losses, 0) AS losses,
    COALESCE(outcome.completed_matches, 0) AS completed_matches, COALESCE(outcome.appearances, 0) AS appearances,
    round(100.0 * outcome.wins / nullif(outcome.completed_matches, 0), 0) AS win_rate
FROM public.club_participants participant LEFT JOIN player_outcomes outcome
    ON outcome.participant_id = participant.id AND outcome.club_id = participant.club_id;
REVOKE ALL ON public.participant_stats FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.participant_stats TO authenticated;

